# 1. SAVE HIGH-QUALITY INDIVIDUAL PLOTS
# ===============================

save_individual_plots <- function(results, output_dir = "metabolomics_plots") {
  
  # Create output directory
  if (!dir.exists(output_dir)) {
    dir.create(output_dir)
  }
  
  cat("Saving individual plots to", output_dir, "\n")
  
  # 1. Partial Dependence Plots
  pd_plots <- create_partial_dependence_plots(results, top_features = 6)
  
  for(i in 1:length(pd_plots)) {
    filename <- file.path(output_dir, paste0("partial_dependence_", i, ".png"))
    ggsave(filename, pd_plots[[i]], width = 6, height = 4, dpi = 300, bg = "white")
    cat("Saved:", filename, "\n")
  }
  
  # 2. Model Comparison Plot
  comparison_plot <- create_model_comparison_plot(results)
  filename <- file.path(output_dir, "model_comparison.png")
  ggsave(filename, comparison_plot, width = 8, height = 6, dpi = 300, bg = "white")
  cat("Saved:", filename, "\n")
  
  # 3. Prediction Distribution Plot
  distribution_plot <- create_prediction_distribution_plot(results)
  filename <- file.path(output_dir, "prediction_distribution.png")
  ggsave(filename, distribution_plot, width = 8, height = 6, dpi = 300, bg = "white")
  cat("Saved:", filename, "\n")
  
  # 4. Feature Correlation Heatmap
  filename <- file.path(output_dir, "correlation_heatmap.png")
  png(filename, width = 8, height = 8, units = "in", res = 300, bg = "white")
  create_feature_correlation_plot(results)
  dev.off()
  cat("Saved:", filename, "\n")
  
  # 5. Combined Partial Dependence Plot
  if(length(pd_plots) >= 4) {
    filename <- file.path(output_dir, "partial_dependence_combined.png")
    combined_plot <- grid.arrange(pd_plots[[1]], pd_plots[[2]], pd_plots[[3]], pd_plots[[4]], 
                                 ncol = 2, top = "Partial Dependence Plots - Top 4 Metabolites")
    ggsave(filename, combined_plot, width = 12, height = 10, dpi = 300, bg = "white")
    cat("Saved:", filename, "\n")
  }
  
  cat("All plots saved successfully!\n")
  return(output_dir)
}

# ===============================
# 2. SAVE TABLES AS CSV/EXCEL
# ===============================

save_tables <- function(results, output_dir = "metabolomics_tables") {
  
  # Create output directory
  if (!dir.exists(output_dir)) {
    dir.create(output_dir)
  }
  
  cat("Saving tables to", output_dir, "\n")
  
  # 1. Model Performance Table
  perf_table <- create_model_performance_table(results)
  write.csv(perf_table, file.path(output_dir, "model_performance.csv"), row.names = FALSE)
  
  # 2. Feature Importance Table
  importance_table <- create_feature_importance_table(results, top_n = 20)
  write.csv(importance_table, file.path(output_dir, "feature_importance.csv"), row.names = FALSE)
  
  # 3. Confusion Matrix Metrics
  cm_tables <- create_confusion_matrix_table(results)
  write.csv(cm_tables$metrics, file.path(output_dir, "confusion_matrix_metrics.csv"), row.names = FALSE)
  write.csv(cm_tables$confusion_matrix, file.path(output_dir, "confusion_matrix.csv"), row.names = FALSE)
  
  # 4. Detailed Results Summary
  summary_data <- data.frame(
    Analysis_Date = Sys.Date(),
    Best_Model = "Ensemble",
    Best_Threshold = results$results$best_threshold,
    Test_Accuracy = results$results$individual_results$Ensemble$accuracy,
    Test_Kappa = results$results$individual_results$Ensemble$kappa,
    Number_Features = length(results$selected_features),
    Test_Samples = nrow(results$test_data)
  )
  write.csv(summary_data, file.path(output_dir, "analysis_summary.csv"), row.names = FALSE)
  
  cat("All tables saved successfully!\n")
  return(output_dir)
}

