# 5. COMPLETE WORKFLOW FUNCTION
# ===============================

save_complete_report <- function(results, base_name = "metabolomics_analysis") {
  
  cat("Creating complete metabolomics report package...\n\n")
  
  # 1. Save individual high-quality plots
  plots_dir <- save_individual_plots(results, paste0(base_name, "_plots"))
  
  # 2. Save all tables
  tables_dir <- save_tables(results, paste0(base_name, "_tables"))
  
  # 3. Create PDF report (requires rmarkdown)
  if(requireNamespace("rmarkdown", quietly = TRUE)) {
    pdf_report <- create_pdf_report(results, paste0(base_name, "_report.pdf"))
  } else {
    cat("rmarkdown not available, skipping PDF report\n")
    pdf_report <- NULL
  }
  
  # 4. Create simple plots PDF
  plots_pdf <- create_plots_pdf(results, paste0(base_name, "_plots.pdf"))
  
  cat("\n=== REPORT PACKAGE CREATED ===\n")
  cat("📁 Plots directory:", plots_dir, "\n")
  cat("📊 Tables directory:", tables_dir, "\n")
  if(!is.null(pdf_report)) {
    cat("📄 PDF report:", pdf_report, "\n")
  }
  cat("📋 Plots PDF:", plots_pdf, "\n")
  
  cat("\nFiles ready for inclusion in your manuscript/presentation!\n")
  
  return(list(
    plots_directory = plots_dir,
    tables_directory = tables_dir,
    pdf_report = pdf_report,
    plots_pdf = plots_pdf
  ))
}


