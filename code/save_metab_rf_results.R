# 4. SIMPLE MULTI-PAGE PDF OF PLOTS
# ===============================

create_plots_pdf <- function(results, output_file = "metabolomics_plots.pdf") {
  
  pdf(output_file, width = 11, height = 8.5, onefile = TRUE)
  
  # Page 1: Model Comparison
  print(create_model_comparison_plot(results))
  
  # Page 2: Prediction Distribution
  print(create_prediction_distribution_plot(results))
  
  # Page 3-6: Partial Dependence Plots
  pd_plots <- create_partial_dependence_plots(results, top_features = 6)
  for(i in 1:min(4, length(pd_plots))) {
    print(pd_plots[[i]])
  }
  
  # Page 7: Combined Partial Dependence
  if(length(pd_plots) >= 4) {
    grid.arrange(pd_plots[[1]], pd_plots[[2]], pd_plots[[3]], pd_plots[[4]], 
                 ncol = 2, top = "Partial Dependence Plots - Top 4 Metabolites")
  }
  
  # Page 8: Correlation Heatmap
  create_feature_correlation_plot(results)
  
  dev.off()
  
  cat("Multi-page PDF saved as:", output_file, "\n")
  return(output_file)
}

